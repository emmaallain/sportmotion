/**
 * Copies the pure game logic (src/game) into supabase/functions/_shared/game so the edge
 * functions run exactly the same rules as the app.
 *
 * Deno needs explicit file extensions, so `from './day'` becomes `from './day.ts'`.
 *
 *   npm run sync:edge            write the copy
 *   npm run sync:edge -- --check fail if the copy is out of date (used by a Jest test)
 */
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative } from 'node:path';

const ROOT = join(__dirname, '..');
export const SOURCE = join(ROOT, 'src', 'game');
export const TARGET = join(ROOT, 'supabase', 'functions', '_shared', 'game');

const HEADER = '// GENERATED by `npm run sync:edge` from src/game — do not edit.\n';

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return name === '__tests__' ? [] : listFiles(path);
    return name.endsWith('.ts') && !name.endsWith('.test.ts') ? [path] : [];
  });
}

/** Rewrites relative imports with the extension Deno expects. */
export function rewriteImports(source: string, file: string): string {
  return source.replace(/(from\s+['"])(\.{1,2}\/[^'"]+)(['"])/g, (_, head, spec, tail) => {
    const base = join(dirname(file), spec);
    if (existsSync(`${base}.ts`)) return `${head}${spec}.ts${tail}`;
    if (existsSync(join(base, 'index.ts'))) return `${head}${spec}/index.ts${tail}`;
    throw new Error(`Cannot resolve import "${spec}" in ${relative(ROOT, file)}`);
  });
}

/** Expected content of the generated directory: relative path → file content. */
export function buildShared(): Map<string, string> {
  const out = new Map<string, string>();
  for (const file of listFiles(SOURCE)) {
    out.set(relative(SOURCE, file), HEADER + rewriteImports(readFileSync(file, 'utf8'), file));
  }
  return out;
}

/** Paths that differ between the expected and the committed copy. */
export function outdated(): string[] {
  const expected = buildShared();
  const actual = existsSync(TARGET) ? listFiles(TARGET).map((f) => relative(TARGET, f)) : [];
  const stale = actual.filter((f) => !expected.has(f));
  const changed = [...expected].filter(
    ([path, content]) =>
      !existsSync(join(TARGET, path)) || readFileSync(join(TARGET, path), 'utf8') !== content,
  );
  return [...stale, ...changed.map(([path]) => path)];
}

function main(): void {
  if (process.argv.includes('--check')) {
    const diff = outdated();
    if (diff.length > 0) {
      console.error(`supabase/functions/_shared/game is out of date:\n  ${diff.join('\n  ')}`);
      console.error('Run `npm run sync:edge`.');
      process.exit(1);
    }
    console.log('Edge shared code is up to date.');
    return;
  }
  rmSync(TARGET, { recursive: true, force: true });
  const files = buildShared();
  for (const [path, content] of files) {
    mkdirSync(dirname(join(TARGET, path)), { recursive: true });
    writeFileSync(join(TARGET, path), content);
  }
  console.log(`Synced ${files.size} files to supabase/functions/_shared/game`);
}

if (require.main === module) main();
