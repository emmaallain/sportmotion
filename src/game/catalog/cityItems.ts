import type { MaterialId } from '../economy/types';
import type { EraId } from '../progression/eras';
import type { CityCategory, CityItem, CityItemKind, Harvest } from './types';

/**
 * XP granted per Pulse spent, by era. Tuned with `npm run simulate` so that a player who
 * completes every day finishes era 1 in ~2 weeks and era 2 in ~6 weeks (see DECISIONS.md).
 */
export const BUILD_XP_RATE: Record<EraId, number> = { 1: 0.1, 2: 0.75, 3: 0.75, 4: 0.75 };

interface Spec {
  id: string;
  category: CityCategory;
  kind?: CityItemKind;
  era: EraId;
  level: number;
  pulses: number;
  materials?: Partial<Record<MaterialId, number>>;
  size?: readonly [number, number];
  tags?: string[];
  requiresRoad?: boolean;
  rotatable?: boolean;
  maxRooms?: number;
  recipes?: string[];
  harvest?: Harvest;
}

function item(spec: Spec): CityItem {
  const size = spec.size ?? [1, 1];
  return {
    id: spec.id,
    category: spec.category,
    kind: spec.kind ?? (spec.category === 'roads' ? 'road' : 'building'),
    era: spec.era,
    level: spec.level,
    cost: { pulses: spec.pulses, materials: spec.materials },
    size,
    sprite: spec.id,
    xp: Math.round(spec.pulses * BUILD_XP_RATE[spec.era]),
    tags: spec.tags ?? [],
    requiresRoad: spec.requiresRoad ?? false,
    rotatable: spec.rotatable ?? size[0] !== size[1],
    maxRooms: spec.maxRooms ?? 0,
    recipes: spec.recipes ?? [],
    harvest: spec.harvest,
  };
}

const decor = (spec: Omit<Spec, 'category' | 'kind'>): CityItem =>
  item({ ...spec, category: 'decoration', kind: 'decor' });

